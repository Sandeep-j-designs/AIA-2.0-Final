import tokens from "@/config/palette-tokens.json";

/**
 * Dev-only reference for the Ink Navy palette (styles/palette.css, generated
 * by scripts/palette/ink-navy.mjs): every primitive ramp, every semantic
 * token in light and dark with where it is used, and the AA checks.
 */

type Semantic = {
  name: string;
  light: string;
  dark: string;
  description: string;
};

const GROUPS: { title: string; prefix: string }[] = [
  { title: "Backgrounds", prefix: "background-" },
  { title: "Foregrounds", prefix: "foreground-" },
  { title: "Borders", prefix: "border-" },
  { title: "Accents", prefix: "accent-" },
];

const Chip = ({ hex }: { hex: string }) => (
  <span className="flex items-center gap-2">
    <span
      className="size-6 shrink-0 rounded-xs border border-pi-line"
      style={{ background: hex }}
    />
    <span className="font-mono text-caption text-pi-body">{hex}</span>
  </span>
);

export default function PaletteReference() {
  const semantic = tokens.semantic as Semantic[];
  return (
    <main className="min-h-screen bg-background">
      <div className="mx-auto max-w-5xl px-6 py-10">
        <p className="text-overline font-semibold uppercase text-pi-faint">
          Foundations · colour
        </p>
        <h1 className="mt-1 text-h1 text-pi-ink">Ink Navy</h1>
        <p className="mt-2 max-w-2xl text-small text-pi-body">
          Primitives, then semantic tokens named by what they colour, then the
          app’s existing names mapped onto them. Generated by{" "}
          <code className="font-mono">scripts/palette/ink-navy.mjs</code>; the
          generator refuses to write a reading pair below WCAG AA.
        </p>

        <section className="mt-10">
          <h2 className="text-h3 text-pi-ink">Primitives</h2>
          <div className="mt-4 space-y-3">
            {Object.entries(tokens.primitives).map(([hue, ramp]) => (
              <div key={hue} className="flex items-center gap-4">
                <span className="w-20 text-small font-medium text-pi-ink">
                  {hue}
                </span>
                <div className="flex flex-1 overflow-hidden rounded-md border border-pi-line">
                  {Object.entries(ramp as Record<string, string>).map(
                    ([step, hex]) => (
                      <div
                        key={step}
                        title={`--color-${hue}-${step} ${hex}`}
                        className="flex h-14 flex-1 items-end p-1.5 text-caption"
                        style={{
                          background: hex,
                          color: Number(step) >= 500 ? "#fff" : "#111827",
                        }}
                      >
                        {step}
                      </div>
                    )
                  )}
                </div>
              </div>
            ))}
          </div>
        </section>

        {GROUPS.map((group) => (
          <section key={group.prefix} className="mt-10">
            <h2 className="text-h3 text-pi-ink">{group.title}</h2>
            <div className="mt-3 overflow-hidden rounded-md border border-pi-line">
              <table className="w-full text-left text-small">
                <thead className="bg-pi-head-bg text-pi-faint">
                  <tr>
                    <th className="px-4 py-2 font-medium">Token</th>
                    <th className="px-4 py-2 font-medium">Light</th>
                    <th className="px-4 py-2 font-medium">Dark</th>
                    <th className="px-4 py-2 font-medium">Used for</th>
                  </tr>
                </thead>
                <tbody>
                  {semantic
                    .filter((t) => t.name.startsWith(group.prefix))
                    .map((t) => (
                      <tr key={t.name} className="border-t border-pi-line">
                        <td className="px-4 py-2 font-mono text-caption text-pi-ink">
                          --{t.name}
                        </td>
                        <td className="px-4 py-2">
                          <Chip hex={t.light} />
                        </td>
                        <td className="px-4 py-2">
                          <Chip hex={t.dark} />
                        </td>
                        <td className="px-4 py-2 text-pi-body">
                          {t.description}
                        </td>
                      </tr>
                    ))}
                </tbody>
              </table>
            </div>
          </section>
        ))}

        <section className="mt-10">
          <h2 className="text-h3 text-pi-ink">Contrast checks</h2>
          <div className="mt-3 overflow-hidden rounded-md border border-pi-line">
            <table className="w-full text-left text-small">
              <thead className="bg-pi-head-bg text-pi-faint">
                <tr>
                  <th className="px-4 py-2 font-medium">Text</th>
                  <th className="px-4 py-2 font-medium">On</th>
                  <th className="px-4 py-2 text-right font-medium">Light</th>
                  <th className="px-4 py-2 text-right font-medium">Dark</th>
                </tr>
              </thead>
              <tbody>
                {tokens.pairs.map((p) => (
                  <tr key={p.fg + p.bg} className="border-t border-pi-line">
                    <td className="px-4 py-2 font-mono text-caption">{p.fg}</td>
                    <td className="px-4 py-2 font-mono text-caption">{p.bg}</td>
                    <td className="px-4 py-2 text-right tabular-nums">
                      {p.light}:1
                    </td>
                    <td className="px-4 py-2 text-right tabular-nums">
                      {p.dark}:1
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </section>
      </div>
    </main>
  );
}
